#!/usr/bin/env python3
"""Generate the CLI capability catalog and matrix from one reviewed source."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/internal/capabilities.json"
MODES = {"API", "页面操作", "人工禁用"}


def validate(data):
    if data.get("schemaVersion") != 1:
        raise ValueError("unsupported capability schemaVersion")
    for key in ("scope", "countingRule"):
        if not isinstance(data.get(key), str) or not data[key].strip():
            raise ValueError(f"missing catalog {key}")
    scenes = data.get("scenarios", [])
    if [s.get("id") for s in scenes] != list(range(1, 29)):
        raise ValueError("scenario IDs must be the ordered, unique original IDs 1–28")
    ids = set()
    for scene in scenes:
        if not scene.get("capabilities"):
            raise ValueError(f"empty scenario {scene['id']}")
        for key in ("name", "help"):
            if not isinstance(scene.get(key), str) or not scene[key].strip():
                raise ValueError(f"missing scenario {scene['id']} {key}")
        for cap in scene["capabilities"]:
            cid = cap.get("id", "")
            if not re.fullmatch(rf"{scene['id']:02d}\.[1-9][0-9]*", cid) or cid in ids:
                raise ValueError(f"invalid or duplicate capability ID: {cid}")
            ids.add(cid)
            if cap.get("mode") not in MODES:
                raise ValueError(f"unknown execution mode for {cid}")
            for key in ("name", "entry", "limits"):
                if not isinstance(cap.get(key), str) or not cap[key].strip():
                    raise ValueError(f"missing capability {cid} {key}")
    return len(ids)


def quote(text):
    return json.dumps(text, ensure_ascii=False)


def cell(text):
    return text.replace("|", r"\|").replace("\n", "<br>")


def render(raw):
    data = json.loads(raw)
    count = validate(data)
    scenes = data["scenarios"]
    digest = hashlib.sha256(raw).hexdigest()
    help_rows = "\n".join(f"  {s['id']:2d} {s['name']}：{s['help']}" for s in scenes)
    go = [
        "// Code generated by scripts/generate_capabilities.py; DO NOT EDIT.",
        "package main", "",
        f"const capabilityCount = {count}",
        f"const capabilityCatalogSHA256 = {quote(digest)}",
        f"const capabilityScenarioHelp = {quote(help_rows)}", "",
        "var capabilityScenarioNames = []string{",
        *[f"\t{quote(s['name'])}," for s in scenes], "}", "",
    ]
    formatted_go = subprocess.run(
        ["gofmt"], input="\n".join(go), text=True, check=True,
        capture_output=True, encoding="utf-8",
    ).stdout
    md = [
        "# 内部能力确认矩阵", "",
        "<!-- Generated by scripts/generate_capabilities.py; edit capabilities.json. -->",
        f"<!-- Source SHA-256: {digest} -->", "",
        f"**{len(scenes)} 个场景，{count} 项能力**。{data['scope']}", "",
        data["countingRule"], "",
        "唯一来源：[capabilities.json](capabilities.json)。运行 `python3 scripts/generate_capabilities.py` 更新本页和 Go 目录；CI 使用 `--check` 拒绝来源与生成文件漂移。", "",
        "场景话术见 [场景清单](../scenarios.md)，执行参数见 [命令参考](../cli-reference.md)。版本回归证据见 [测试记录](test-results.md)。", "",
        "模式说明：API 表示该入口使用同源 API 或本地 CLI 组合，不意味着每项参数已全面线上验收；页面操作必须核验真实选区与持久化结果；人工禁用表示 CLI/Agent 不代用户操作。", "",
    ]
    for title, selected in [("文件与位置", scenes[:15]), ("编辑与协作", scenes[15:])]:
        subtotal = sum(len(s["capabilities"]) for s in selected)
        md += [f"## {title}（{subtotal} 项）", "",
               "| 能力 ID | 场景 | 能力 | 执行方式 | 入口 | 范围与限制 |",
               "|---|---|---|---|---|---|"]
        for scene in selected:
            for cap in scene["capabilities"]:
                values = [cap["id"], f"{scene['id']} {scene['name']}", cap["name"], cap["mode"], cap["entry"], cap["limits"]]
                md.append("| " + " | ".join(cell(v) for v in values) + " |")
        md.append("")
    md += ["## 共同边界", "",
           "- 文件锁定、限制编辑、高级权限、成员级授权和彻底删除均需网页人工操作；CLI 删除只进回收站。",
           "- 导入默认私有，权限变更与导入是不同操作。",
           "- 页面未加载、SDK 不存在或验证失败时必须报告失败，不以面板打开代替操作完成。",
           "- 浏览器优先级仅在 [场景清单](../scenarios.md#浏览器优先级) 维护。",
           "- 需求场景 29–42 的实现与验收另见 [阶段实测记录](../phase3-acceptance.md)，不计入本目录，也不能用本目录替代线上证据。", ""]
    return {ROOT / "cli/capabilities_generated.go": formatted_go,
            ROOT / "docs/internal/capability-matrix.md": "\n".join(md)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ; do not write")
    args = parser.parse_args()
    outputs = render(SOURCE.read_bytes())
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("Capability outputs are stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Capability outputs match source." if args.check else "Generated CLI catalog and internal capability matrix.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, KeyError, TypeError, OSError, subprocess.CalledProcessError) as exc:
        print(f"Capability generation failed: {exc}", file=sys.stderr)
        raise SystemExit(1)
